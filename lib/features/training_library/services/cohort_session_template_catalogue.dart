  static const seedIdPrefix = 'TMP-';

  static bool isCanonicalSeedId(String protocolId) {
    final id = protocolId.trim();
    if (!id.startsWith(seedIdPrefix)) return false;
    final suffix = id.substring(seedIdPrefix.length);
    return RegExp(r'^\d{3}$').hasMatch(suffix);
  }

