    required String suitableFor,
    required String physiologicalDemand,
    required String recoveryCost,
    required SessionIntent primaryIntent,
    required List<ProtocolStepDraft> steps,
    String? optionalEquipment,
    String? secondaryCapability,
    bool? runningRequired,
    bool? runningReplaceable,
    bool? hotelFriendly,
    bool? indoorFriendly,
